"""
SmartSeed AI Engine — Response schemas.
Pydantic models for all API response payloads.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Anomaly Detection
# ---------------------------------------------------------------------------


class AnomalyResult(BaseModel):
    """A single detected anomaly with supporting evidence."""

    anomaly_type: str = Field(
        ...,
        description="Machine-readable anomaly category (e.g. 'duplicate_scan', 'geo_inconsistency')",
    )
    severity: str = Field(
        ...,
        description="Severity level: info | warning | high | critical",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Model confidence in this detection (0.0–1.0)",
    )
    description: str = Field(..., description="Human-readable description of the anomaly")
    evidence: list[str] = Field(default_factory=list, description="List of supporting evidence strings")
    recommended_action: str = Field(..., description="Suggested remediation step")


class AnomalyDetectionResponse(BaseModel):
    """Response from the anomaly-detection endpoint."""

    batch_id: str
    anomalies: list[AnomalyResult] = Field(default_factory=list)
    total_anomalies: int = Field(..., ge=0)
    max_severity: str = Field(default="info", description="Highest severity across all anomalies")
    model_version: str
    analyzed_at: datetime


# ---------------------------------------------------------------------------
# Risk Scoring
# ---------------------------------------------------------------------------


class RiskIndicator(BaseModel):
    """An individual weighted signal that contributed to the risk score."""

    category: str = Field(..., description="Signal category (e.g. 'duplicate_scan')")
    signal: str = Field(..., description="Short human-readable signal name")
    weight: float = Field(..., ge=0.0, le=1.0, description="Category weight")
    normalized_score: float = Field(..., ge=0.0, le=1.0, description="Normalised signal value")
    description: str = Field(..., description="Explanation of why this signal matters")


class RiskScoreResponse(BaseModel):
    """Response from the risk-scoring endpoint."""

    batch_id: str
    score: int = Field(..., ge=0, le=100, description="Overall risk score 0–100")
    risk_level: str = Field(..., description="Risk category: low | medium | high | critical")
    indicators: list[RiskIndicator] = Field(default_factory=list)
    recommended_action: str
    model_version: str
    calculated_at: datetime


# ---------------------------------------------------------------------------
# Investigation
# ---------------------------------------------------------------------------


class InvestigationEvidence(BaseModel):
    """A single piece of investigation evidence."""

    type: str = Field(..., description="Evidence category (scan, transfer, anomaly, etc.)")
    description: str = Field(..., description="Human-readable description")
    data: dict[str, Any] = Field(default_factory=dict, description="Raw evidence payload")
    timestamp: datetime


class TimelineEvent(BaseModel):
    """A chronological event in the investigation timeline."""

    timestamp: datetime
    event: str = Field(..., description="Short event title")
    details: str = Field(..., description="Narrative details")


class InvestigationResponse(BaseModel):
    """Full investigation report generated by the investigation agent."""

    investigation_id: str
    batch_id: str
    risk_score: int = Field(..., ge=0, le=100)
    risk_category: str
    main_suspicious_activity: str
    supporting_evidence: list[InvestigationEvidence] = Field(default_factory=list)
    timeline: list[TimelineEvent] = Field(default_factory=list)
    potential_explanation: str
    recommended_steps: list[str] = Field(default_factory=list)
    confidence: float = Field(..., ge=0.0, le=1.0)
    limitations: list[str] = Field(default_factory=list)
    generated_at: datetime


# ---------------------------------------------------------------------------
# Model Info
# ---------------------------------------------------------------------------


class ModelInfoResponse(BaseModel):
    """Metadata about loaded ML models."""

    model_version: str
    models: dict[str, Any] = Field(default_factory=dict)
    capabilities: list[str] = Field(default_factory=list)
    training_status: str = Field(default="untrained")


class RetrainResponse(BaseModel):
    """Acknowledgement for a retrain request."""

    status: str
    message: str
    model_version: str
